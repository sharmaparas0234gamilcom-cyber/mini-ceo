export function getAchievementTemplate(id: string): AchievementTemplate | undefined {
  return ACHIEVEMENT_TEMPLATES.find(a => a.id === id)
}

export function getAchievementsByCategory(category: AchievementTemplate['category']): AchievementTemplate[] {
  return ACHIEVEMENT_TEMPLATES.filter(a => a.category === category)
}

export function getAchievementsByRarity(rarity: AchievementTemplate['rarity']): AchievementTemplate[] {
  return ACHIEVEMENT_TEMPLATES.filter(a => a.rarity === rarity)
}